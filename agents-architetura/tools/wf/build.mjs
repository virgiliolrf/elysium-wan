#!/usr/bin/env node
// Builds self-contained workflow scripts: agents-architetura/tools/wf/src/<name>.js -> .claude/workflows/<name>.js
//
// Workflow scripts cannot import, so shared code lives in agents-architetura/tools/wf/lib/*.js and
// is spliced in at `// @include <name>` lines. The build also enforces the
// runtime contract up front: meta is a pure literal that starts the file,
// meta.name matches the file name, every phase title used is declared in
// meta.phases, no Date.now()/Math.random()/new Date() (they break resume),
// <= 512 KiB, and the result parses.
//
//   node agents-architetura/tools/wf/build.mjs           build all
//   node agents-architetura/tools/wf/build.mjs --check   fail if any generated file is stale or orphaned (CI)
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..', '..', '..')
const LIB = join(HERE, 'lib')
const SRC = join(HERE, 'src')
const OUT = join(ROOT, '.claude', 'workflows')
export const MAX_BYTES = 524288
export const GENERATED_MARK = '// GENERATED by agents-architetura/tools/wf/build.mjs'
const NONDETERMINISM = /\bDate\s*\.\s*now\b|\bMath\s*\.\s*random\b|\bnew\s+Date\s*\(\s*\)/
const META_START = 'export const meta = {'

export function extractMeta(script) {
  if (!script.startsWith(META_START)) throw new Error('script must begin with `export const meta = {`')
  let depth = 0
  let quote = null
  let i = META_START.length - 1
  for (; i < script.length; i++) {
    const c = script[i]
    if (quote) {
      if (c === '\\') i++
      else if (c === quote) quote = null
      continue
    }
    if (c === "'" || c === '"' || c === '`') quote = c
    else if (c === '/' && (script[i + 1] === '/' || script[i + 1] === '*')) throw new Error('meta must not contain comments')
    else if (c === '{') depth++
    else if (c === '}' && --depth === 0) break
  }
  if (depth !== 0) throw new Error('unterminated meta object')
  const text = script.slice(META_START.length - 1, i + 1)
  if (text.includes('${')) throw new Error('meta must be a pure literal (no template interpolation)')
  if (/\.\.\./.test(text.replace(/(['"`])(?:\\.|(?!\1).)*\1/g, ''))) throw new Error('meta must be a pure literal (no spreads)')
  let meta
  try {
    meta = vm.runInNewContext(`(${text})`, Object.create(null))
  } catch (e) {
    throw new Error(`meta is not a pure literal: ${e.message}`)
  }
  return { meta, end: i + 1 }
}

export function expandIncludes(body, libDir = LIB) {
  const seen = new Set()
  return body.replace(/^\/\/ @include ([a-z0-9-]+)[ \t]*$/gm, (_, name) => {
    if (seen.has(name)) throw new Error(`lib "${name}" included twice`)
    seen.add(name)
    const p = join(libDir, `${name}.js`)
    if (!existsSync(p)) throw new Error(`unknown include: ${name}`)
    const lib = readFileSync(p, 'utf8')
    if (/^\s*(import|export)\s/m.test(lib)) throw new Error(`lib/${name}.js must not import/export (scripts are self-contained)`)
    return `// ---- begin lib/${name}.js ----\n${lib.trimEnd()}\n// ---- end lib/${name}.js ----`
  })
}

export function checkPhases(meta, body) {
  const declared = new Set((meta.phases ?? []).map(p => p.title))
  const used = new Set([...body.matchAll(/\bphase\(\s*'([^']+)'\s*\)/g)].map(m => m[1]))
  for (const m of body.matchAll(/\bphase:\s*'([^']+)'/g)) used.add(m[1])
  const missing = [...used].filter(t => !declared.has(t)).sort()
  if (missing.length) throw new Error(`phase titles used but not declared in meta.phases: ${missing.join(', ')}`)
}

export function buildScript(src, { name, libDir = LIB } = {}) {
  const { meta, end } = extractMeta(src)
  if (typeof meta.name !== 'string' || typeof meta.description !== 'string') throw new Error('meta.name and meta.description are required strings')
  if (name && meta.name !== name) throw new Error(`meta.name "${meta.name}" must equal the file name "${name}"`)
  const body = expandIncludes(src.slice(end), libDir)
  checkPhases(meta, body)
  const script = `${src.slice(0, end)}\n\n${GENERATED_MARK} from agents-architetura/tools/wf/src/${meta.name}.js — edit the source, then rebuild.${body}`
  if (NONDETERMINISM.test(script)) throw new Error('workflow scripts must be deterministic: Date.now()/Math.random()/new Date() are unavailable')
  const bytes = Buffer.byteLength(script)
  if (bytes > MAX_BYTES) throw new Error(`script is ${bytes} bytes; runtime limit is ${MAX_BYTES}`)
  try {
    new vm.Script(`(async () => {\n${script.replace(/^export const meta =/, 'const meta =')}\n})`)
  } catch (e) {
    throw new Error(`generated script does not parse: ${e.message}`)
  }
  return { meta, script }
}

export function buildAll({ check = false, srcDir = SRC, outDir = OUT, libDir = LIB } = {}) {
  const problems = []
  const built = []
  const sources = readdirSync(srcDir).filter(f => f.endsWith('.js')).sort()
  if (!check) mkdirSync(outDir, { recursive: true })
  for (const f of sources) {
    const name = basename(f, '.js')
    const target = join(outDir, f)
    try {
      const { script } = buildScript(readFileSync(join(srcDir, f), 'utf8'), { name, libDir })
      if (check) {
        if (!existsSync(target) || readFileSync(target, 'utf8') !== script) problems.push(`${f}: stale — run node agents-architetura/tools/wf/build.mjs`)
      } else {
        writeFileSync(target, script)
      }
      built.push(name)
    } catch (e) {
      problems.push(`${f}: ${e.message}`)
    }
  }
  if (existsSync(outDir)) {
    for (const f of readdirSync(outDir).filter(f => f.endsWith('.js'))) {
      const generated = readFileSync(join(outDir, f), 'utf8').includes(GENERATED_MARK)
      if (generated && !sources.includes(f)) problems.push(`${f}: generated file has no source in agents-architetura/tools/wf/src (orphan)`)
    }
  }
  return { built, problems }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  const { built, problems } = buildAll({ check })
  for (const p of problems) console.error(`wf-build: ${p}`)
  if (problems.length) process.exit(1)
  console.log(`wf-build: ${check ? 'up to date' : 'built'}: ${built.join(', ') || '(no sources)'}`)
}
